import matplotlib.pyplot as plt

days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]

steps = [4500, 6000, 7500, 5000, 8000, 10000, 9000]
water = [2, 2.5, 3, 2, 2.5, 3.5, 3]

plt.figure(figsize=(9, 7))

# First subplot: Daily steps
plt.subplot(2, 1, 1)
plt.plot(days, steps, marker="o", color="green")
plt.title("Daily Step Count")
plt.ylabel("Number of Steps")
plt.grid(True)

# Second subplot: Water intake
plt.subplot(2, 1, 2)
plt.plot(days, water, marker="o", color="blue")
plt.title("Daily Water Intake")
plt.xlabel("Day")
plt.ylabel("Water (Litres)")
plt.grid(True)

plt.tight_layout()
plt.show()

import matplotlib.pyplot as plt

quarters = ["Q1", "Q2", "Q3", "Q4"]
posts = [15, 22, 18, 30]

fig, axes = plt.subplots(2, 2, figsize=(10, 8))

# 1. Line chart
axes[0, 0].plot(quarters, posts, marker="o", color="blue")
axes[0, 0].set_title("Quarterly Posts - Line Chart")
axes[0, 0].set_ylabel("Number of Posts")
axes[0, 0].grid(True)

# 2. Bar chart
axes[0, 1].bar(quarters, posts, color="orange")
axes[0, 1].set_title("Quarterly Posts - Bar Chart")
axes[0, 1].set_ylabel("Number of Posts")

# 3. Scatter plot
axes[1, 0].scatter(quarters, posts, color="purple", s=80)
axes[1, 0].set_title("Quarterly Posts - Scatter Plot")
axes[1, 0].set_ylabel("Number of Posts")
axes[1, 0].grid(True)

# 4. Pie chart
axes[1, 1].pie(
    posts,
    labels=quarters,
    autopct="%1.1f%%"
)
axes[1, 1].set_title("Quarterly Posts - Pie Chart")

fig.suptitle("Instagram Posts by Quarter")
fig.tight_layout()
plt.show()

import matplotlib.pyplot as plt

months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun"]

zomato = [5, 7, 6, 8, 9, 7]
swiggy = [4, 6, 8, 7, 6, 9]
dominos = [2, 3, 4, 3, 5, 4]

fig, axes = plt.subplots(
    1, 3,
    figsize=(13, 4),
    sharey=True
)

# Zomato
axes[0].plot(months, zomato, marker="o", color="red")
axes[0].set_title("Zomato Orders")
axes[0].set_ylabel("Number of Orders")
axes[0].grid(True)

# Swiggy
axes[1].plot(months, swiggy, marker="o", color="orange")
axes[1].set_title("Swiggy Orders")
axes[1].grid(True)

# Domino's
axes[2].plot(months, dominos, marker="o", color="blue")
axes[2].set_title("Domino's Orders")
axes[2].grid(True)

for ax in axes:
    ax.set_xlabel("Month")
    ax.tick_params(axis="x", rotation=45)

fig.suptitle("Monthly Food Orders Comparison")
fig.tight_layout()
plt.show()

