import matplotlib.pyplot as plt

apps = ["Zomato", "Swiggy", "Uber Eats", "Dunzo", "Domino's"]
orders = [120, 150, 80, 60, 100]

colors = ["red", "orange", "blue", "green", "purple"]

bars = plt.bar(apps, orders, color=colors)

# Add order counts above each bar
for bar in bars:
    height = bar.get_height()

    plt.text(
        bar.get_x() + bar.get_width() / 2,
        height,
        str(height),
        ha="center",
        va="bottom"
    )

plt.title("Daily Orders by Food Delivery App")
plt.xlabel("Food Delivery Apps")
plt.ylabel("Number of Orders")

plt.show()

