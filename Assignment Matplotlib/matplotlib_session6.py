import matplotlib.pyplot as plt
import numpy as np

friends = [
    "Aarav", "Riya", "Rahul", "Priya", "Neha", "Aman",
    "Sneha", "Karan", "Ananya", "Vikram", "Isha", "Arjun"
]

orders = np.array([2, 5, 3, 8, 4, 6, 1, 7, 5, 9, 3, 6])
spending = np.array([
    400, 1200, 650, 2000, 900, 1500,
    250, 1800, 1100, 2400, 700, 1600
])

# Scatter plot
plt.scatter(orders, spending, color="teal", label="Friends")

# Add friend names
for i in range(len(friends)):
    plt.annotate(
        friends[i],
        (orders[i], spending[i]),
        xytext=(5, 5),
        textcoords="offset points"
    )

# Calculate slope and intercept
slope, intercept = np.polyfit(orders, spending, 1)

# Generate regression line
x_line = np.linspace(orders.min(), orders.max(), 100)
y_line = slope * x_line + intercept

plt.plot(
    x_line,
    y_line,
    color="red",
    linestyle="--",
    label="Best-fit line"
)

plt.title("Zomato Orders vs Spending with Trend Line")
plt.xlabel("Number of Orders")
plt.ylabel("Total Spending (₹)")
plt.legend()
plt.grid(True)

print("Slope:", round(slope, 2))
print("Intercept:", round(intercept, 2))
plt.show()

import matplotlib.pyplot as plt
import numpy as np

# Daily usage hours for 15 users
youtube_hours = np.array([
    1, 2, 3, 4, 1.5, 2.5, 5, 3.5, 4.5, 2,
    6, 5.5, 3, 1.5, 4
])

spotify_hours = np.array([
    0.5, 1, 1.5, 2, 1, 1.2, 2.5, 1.8, 2.2, 0.8,
    3, 2.7, 1.6, 0.7, 2.1
])

# Fit the regression line
slope, intercept = np.polyfit(youtube_hours, spotify_hours, 1)

# Generate points for the line
x_line = np.linspace(
    youtube_hours.min(),
    youtube_hours.max(),
    100
)
y_line = slope * x_line + intercept

# Plot the data and regression line
plt.scatter(
    youtube_hours,
    spotify_hours,
    color="blue",
    label="Users"
)

plt.plot(
    x_line,
    y_line,
    color="red",
    label="Regression Line"
)

# Display equation
equation = f"y = {slope:.2f}x + {intercept:.2f}"

plt.text(
    0.05, 0.95,
    equation,
    transform=plt.gca().transAxes,
    verticalalignment="top",
    bbox=dict(facecolor="white", alpha=0.8)
)

plt.title("YouTube vs Spotify Usage")
plt.xlabel("YouTube Watch Hours per Day")
plt.ylabel("Spotify Listening Hours per Day")
plt.legend()
plt.grid(True)

plt.show()

