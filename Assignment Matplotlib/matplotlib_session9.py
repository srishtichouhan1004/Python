import matplotlib.pyplot as plt

days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]

zomato_orders = [5, 7, 6, 8, 10, 12, 9]
swiggy_orders = [4, 6, 5, 7, 8, 10, 11]

plt.figure(figsize=(9, 5))

plt.bar(days, zomato_orders, color="tomato", label="Zomato")
plt.bar(
    days,
    swiggy_orders,
    bottom=zomato_orders,
    color="orange",
    label="Swiggy"
)

plt.title("Daily Food Orders: Zomato vs Swiggy")
plt.xlabel("Day")
plt.ylabel("Number of Orders")
plt.legend()
plt.show()

