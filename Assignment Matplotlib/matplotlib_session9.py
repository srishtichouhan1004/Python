import matplotlib.pyplot as plt

days = list(range(1, 11))

# Average delivery time in minutes
avg_delivery = [35, 38, 34, 40, 37, 42, 36, 39, 33, 38]

# Standard deviation for each day
std_deviation = [3, 4, 2, 5, 3, 4, 2, 3, 2, 4]

plt.figure(figsize=(9, 5))

plt.errorbar(
    days,
    avg_delivery,
    yerr=std_deviation,
    fmt="o-",
    color="purple",
    ecolor="gray",
    capsize=5,
    label="Average Delivery Time"
)

plt.title("Flipkart Delivery Time with Standard Deviation")
plt.xlabel("Day")
plt.ylabel("Delivery Time (minutes)")
plt.xticks(days)
plt.legend()
plt.grid(True)
plt.show()

import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from datetime import datetime, timedelta

# Example 14-day period
start_date = datetime(2026, 6, 1)

dates = [
    start_date + timedelta(days=i)
    for i in range(14)
]

# Illustrative wallet balances in rupees
balance = [
    2500, 2200, 2400, 1800, 2000, 1700, 2100,
    1900, 2300, 1600, 2000, 1800, 2200, 2600
]

fig, ax = plt.subplots(figsize=(10, 5))

ax.plot(dates, balance, marker="o", color="teal")

ax.set_title("Paytm Wallet Balance Over 14 Days")
ax.set_xlabel("Date")
ax.set_ylabel("Wallet Balance (₹)")

# Format dates as DD MMM, e.g. 12 Jun
ax.xaxis.set_major_formatter(mdates.DateFormatter("%d %b"))

fig.autofmt_xdate()
ax.grid(True)

plt.tight_layout()
plt.show()

