import pandas as pd
import matplotlib.pyplot as plt

# Create a sample sales dataset
data = {
    "product": [
        "Laptop", "T-Shirt", "Rice", "Mobile", "Jeans",
        "Wheat", "Headphones", "Shirt", "Oil", "Tablet",
        "Laptop", "T-Shirt", "Rice", "Mobile", "Jeans",
        "Wheat", "Headphones", "Shirt", "Oil", "Tablet",
        "Laptop", "T-Shirt", "Rice", "Mobile", "Jeans",
        "Wheat", "Headphones", "Shirt", "Oil", "Tablet"
    ],

    "category": [
        "Electronics", "Clothing", "Groceries", "Electronics",
        "Clothing", "Groceries", "Electronics", "Clothing",
        "Groceries", "Electronics",
        "Electronics", "Clothing", "Groceries", "Electronics",
        "Clothing", "Groceries", "Electronics", "Clothing",
        "Groceries", "Electronics",
        "Electronics", "Clothing", "Groceries", "Electronics",
        "Clothing", "Groceries", "Electronics", "Clothing",
        "Groceries", "Electronics"
    ],

    "date": [
        "2025-01-05", "2025-01-12", "2025-01-20",
        "2025-02-03", "2025-02-15", "2025-02-22",
        "2025-03-04", "2025-03-11", "2025-03-19",
        "2025-03-25", "2025-04-02", "2025-04-10",
        "2025-04-18", "2025-05-06", "2025-05-14",
        "2025-05-21", "2025-06-03", "2025-06-12",
        "2025-06-19", "2025-06-27", "2025-07-05",
        "2025-07-13", "2025-07-20", "2025-08-02",
        "2025-08-10", "2025-08-18", "2025-09-04",
        "2025-10-12", "2025-11-15", "2025-12-20"
    ],

    "sales_amount": [
        55000, 1200, 2500, 40000, 2200,
        1800, 2500, 1500, 1200, 30000,
        60000, 1800, 3000, 45000, 2500,
        2000, 2800, 1700, 1500, 35000,
        65000, 2000, 2800, 50000, 2700,
        2200, 3200, 1900, 1800, 40000
    ]
}

# Convert dictionary to DataFrame
df = pd.DataFrame(data)

# Convert date column to datetime format
df["date"] = pd.to_datetime(df["date"])

# Save the dataset as a CSV file
df.to_csv("sales_data.csv", index=False)

# Display the first five rows
print("First five rows of the dataset:")
print(df.head())

# Calculate total sales for each category
category_sales = df.groupby("category")["sales_amount"].sum()

# Create the bar chart
plt.figure(figsize=(8, 5))

plt.bar(
    category_sales.index,
    category_sales.values,
    color=["royalblue", "orange", "seagreen"]
)

plt.title("Total Sales by Product Category")
plt.xlabel("Product Category")
plt.ylabel("Total Sales (₹)")

plt.tight_layout()
plt.show()

# Set date as the index
monthly_df = df.set_index("date")

# Calculate total sales per month
monthly_sales = monthly_df["sales_amount"].resample("MS").sum()

# Create the line chart
plt.figure(figsize=(10, 5))

plt.plot(
    monthly_sales.index,
    monthly_sales.values,
    marker="o",
    color="purple",
    linewidth=2
)

plt.title("Monthly Sales Trend - 2025")
plt.xlabel("Month")
plt.ylabel("Total Sales (₹)")

plt.xticks(monthly_sales.index, monthly_sales.index.strftime("%b"))
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 5))

plt.hist(
    df["sales_amount"],
    bins=10,
    color="skyblue",
    edgecolor="black"
)

plt.title("Distribution of Order Amounts")
plt.xlabel("Order Amount (₹)")
plt.ylabel("Number of Orders")

plt.grid(axis="y", alpha=0.3)
plt.tight_layout()
plt.show()

# Calculate category-wise sales
category_sales = df.groupby("category")["sales_amount"].sum()

fig, ax = plt.subplots(figsize=(9, 5))

bars = ax.bar(
    category_sales.index,
    category_sales.values,
    color=["royalblue", "orange", "seagreen"]
)

# Add sales values above each bar
for bar in bars:
    height = bar.get_height()

    ax.annotate(
        f"₹{height:,.0f}",
        xy=(bar.get_x() + bar.get_width() / 2, height),
        xytext=(0, 5),
        textcoords="offset points",
        ha="center",
        va="bottom"
    )

ax.set_title("Category Sales KPI Dashboard")
ax.set_xlabel("Product Category")
ax.set_ylabel("Total Sales (₹)")
ax.grid(axis="y", alpha=0.3)

fig.tight_layout()

# Export the chart
fig.savefig(
    "category_sales_kpi.png",
    dpi=150,
    bbox_inches="tight"
)

plt.show()

