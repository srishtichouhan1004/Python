import matplotlib.pyplot as plt

days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
steps = [4500, 6000, 7500, 5200, 8000, 10000, 9000]

fig, ax = plt.subplots(figsize=(9, 5))

ax.plot(
    days,
    steps,
    marker="o",
    linewidth=2,
    color="darkgreen"
)

ax.set_title("Daily Step Count")
ax.set_xlabel("Day")
ax.set_ylabel("Number of Steps")
ax.grid(True)

fig.tight_layout()

# Save the first PDF
fig.savefig(
    "steps_150dpi.pdf",
    dpi=150,
    bbox_inches="tight"
)

# Save the second PDF at higher DPI
fig.savefig(
    "steps_300dpi.pdf",
    dpi=300,
    bbox_inches="tight"
)

plt.show()

