import matplotlib.pyplot as plt

restaurants = [
    "Restaurant A",
    "Restaurant B",
    "Restaurant C",
    "Restaurant D",
    "Restaurant E"
]

orders = [120, 95, 150, 80, 110]

plt.figure(figsize=(8, 5))
plt.bar(restaurants, orders, color="tomato")

plt.title("Orders by Zomato Restaurant")
plt.xlabel("Restaurants")
plt.ylabel("Number of Orders")
plt.tight_layout()

# Save as PNG with 150 DPI
plt.savefig("zomato_orders.png", dpi=150, bbox_inches="tight")

# Display the chart
plt.show()

import matplotlib.pyplot as plt

