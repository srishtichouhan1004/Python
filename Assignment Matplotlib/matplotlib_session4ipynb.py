import matplotlib.pyplot as plt

categories = [
    "Food Delivery",
    "Shopping",
    "Entertainment",
    "UPI Payments"
]

spending = [3000, 6000, 1500, 2500]

fig, ax = plt.subplots()

ax.pie(
    spending,
    labels=categories,
    autopct="%1.1f%%",
    startangle=90
)

# Add a white circle at the center
centre_circle = plt.Circle(
    (0, 0),
    0.60,
    color="white"
)

ax.add_artist(centre_circle)

ax.set_title("Monthly Online Spending Donut Chart")
ax.axis("equal")

plt.show()

