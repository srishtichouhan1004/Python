import matplotlib.pyplot as plt

months = ["Jan", "Feb", "Mar", "Apr", "May"]

zomato_orders = [5, 7, 6, 9, 10]
swiggy_orders = [6, 5, 8, 7, 9]

plt.plot(
    months,
    zomato_orders,
    color="red",
    linestyle="-",
    marker="o",
    label="Zomato"
)

plt.plot(
    months,
    swiggy_orders,
    color="orange",
    linestyle="--",
    marker="s",
    label="Swiggy"
)

plt.title("Monthly Orders: Zomato vs Swiggy")
plt.xlabel("Month")
plt.ylabel("Number of Orders")
plt.legend()
plt.grid(True)
plt.show()

