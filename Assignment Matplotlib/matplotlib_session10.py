import matplotlib.pyplot as plt

months = [
    "Jan", "Feb", "Mar", "Apr", "May", "Jun",
    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"
]

active_users = [
    1200, 1350, 1280, 1500, 1650, 1800,
    1750, 1900, 2100, 2050, 2300, 2500
]

plt.figure(figsize=(10, 5))

plt.plot(months, active_users, marker="o", color="green")

# Find the month with the highest user count
max_index = active_users.index(max(active_users))

plt.annotate(
    f"Highest: {active_users[max_index]} users",
    xy=(months[max_index], active_users[max_index]),
    xytext=(-80, -40),
    textcoords="offset points",
    arrowprops=dict(arrowstyle="->", color="red"),
    bbox=dict(boxstyle="round,pad=0.4", fc="lightyellow")
)

plt.title("Monthly Daily Active Users")
plt.xlabel("Month")
plt.ylabel("Daily Active Users")
plt.grid(True)
plt.tight_layout()
plt.show()

import matplotlib.pyplot as plt

months = [
    "Jan", "Feb", "Mar", "Apr", "May", "Jun",
    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"
]

orders = [450, 380, 520, 600, 480, 700, 650, 750, 580, 800, 720, 900]

plt.figure(figsize=(10, 5))

plt.bar(months, orders, color="orange")

# Find the month with the lowest orders
min_index = orders.index(min(orders))

plt.annotate(
    f"Lowest: {orders[min_index]} orders",
    xy=(min_index, orders[min_index]),
    xytext=(min_index + 1.5, orders[min_index] + 180),
    arrowprops=dict(arrowstyle="->", color="red", lw=1.5),
    bbox=dict(boxstyle="round,pad=0.4", fc="lightyellow")
)

plt.title("Monthly Zomato Orders")
plt.xlabel("Month")
plt.ylabel("Number of Orders")
plt.grid(axis="y", alpha=0.3)
plt.tight_layout()
plt.show()

