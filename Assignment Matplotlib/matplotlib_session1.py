import matplotlib.pyplot as plt

days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]

# Daily usage in hours (sample data)
spotify_hours = [1.5, 2, 1, 2.5, 2, 3, 2.5]
youtube_hours = [1, 1.5, 2, 1, 2.5, 3.5, 2]

# Create one figure with two Axes side by side
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

# Spotify plot
ax1.plot(days, spotify_hours, marker="o", color="green")
ax1.set_title("Daily Spotify Listening")
ax1.set_xlabel("Day")
ax1.set_ylabel("Listening Hours")
ax1.grid(True)

# YouTube plot
ax2.plot(days, youtube_hours, marker="o", color="red")
ax2.set_title("Daily YouTube Viewing")
ax2.set_xlabel("Day")
ax2.set_ylabel("Viewing Hours")
ax2.grid(True)

# Overall figure title
fig.suptitle("Weekly Media Usage Dashboard")

# Adjust spacing
fig.tight_layout()
plt.show()

