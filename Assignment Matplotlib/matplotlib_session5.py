import matplotlib.pyplot as plt

steps = [
    4200, 5100, 6300, 7000, 8500, 9200, 4800,
    5600, 6100, 7500, 8100, 9000, 10200, 6800,
    7200, 8300, 9500, 11000, 5900, 6400, 7800,
    8700, 9800, 10500, 4500, 5300, 6700, 7600,
    8900, 11500
]

fig, axes = plt.subplots(1, 2, figsize=(12, 4))

# Histogram showing frequency
axes[0].hist(steps, bins=6, edgecolor="black")
axes[0].set_title("Daily Steps: Frequency")
axes[0].set_xlabel("Steps")
axes[0].set_ylabel("Number of Days")

# Histogram showing density
axes[1].hist(steps, bins=6, density=True, edgecolor="black")
axes[1].set_title("Daily Steps: Density")
axes[1].set_xlabel("Steps")
axes[1].set_ylabel("Probability Density")

plt.tight_layout()
plt.show()

