import requests
from bs4 import BeautifulSoup

url = "https://www.zomato.com"

response = requests.get(url, timeout=30)

soup = BeautifulSoup(response.text, "html.parser")

unique_classes = set()

for div in soup.find_all("div"):
    classes = div.get("class", [])

    for class_name in classes:
        unique_classes.add(class_name)

print("Total unique class names:", len(unique_classes))
print("\nUnique class names:")

for class_name in sorted(unique_classes):
    print(class_name)

import requests
from bs4 import BeautifulSoup

url = "https://in.bookmyshow.com/"

response = requests.get(url, timeout=30)

soup = BeautifulSoup(response.text, "html.parser")

elements_with_id = soup.find_all(attrs={"id": True})

print("Total elements with an id attribute:",
      len(elements_with_id))

for element in elements_with_id:
    print(
        "Tag:", element.name,
        "| ID:", element.get("id")
    )

