import re
from bs4 import BeautifulSoup

def clean_summary(summary):
    """Remove HTML tags and extra whitespace from a summary."""
    if not summary:
        return ""

    # Convert HTML content into plain text
    text = BeautifulSoup(summary, "html.parser").get_text(" ")

    # Replace repeated whitespace with a single space
    text = re.sub(r"\s+", " ", text).strip()

    return text


def get_tag_text(item, tag_names):
    """Return the first non-empty value found among candidate XML tags."""
    for tag_name in tag_names:
        tag = item.find(tag_name)

        if tag:
            value = tag.get_text(" ", strip=True)
            if value:
                return value

    return ""


news_data = []

for item in articles:
    title = get_tag_text(item, ["title"])
    author = get_tag_text(
        item,
        ["dc:creator", "author", "creator"]
    )
    publication_date = get_tag_text(
        item,
        ["pubDate", "published", "updated", "dc:date"]
    )
    raw_summary = get_tag_text(
        item,
        ["description", "content:encoded", "summary"]
    )

    # Clean the summary before deciding whether to keep the article
    summary = clean_summary(raw_summary)

    # Skip articles with missing or empty summaries
    if not summary:
        continue

    news_data.append({
        "title": title,
        "author": author if author else "Unknown",
        "publication_date": publication_date,
        "summary": summary
    })

    # Collect 10 articles with non-empty summaries
    if len(news_data) == 10:
        break

print("Articles collected:", len(news_data))

