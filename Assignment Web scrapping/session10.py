import requests
import pandas as pd
import re
from bs4 import BeautifulSoup

url = "https://www.theverge.com/rss/tech/index.xml"

response = requests.get(
    url,
    headers={"User-Agent": "Mozilla/5.0"},
    timeout=30
)
response.raise_for_status()

soup = BeautifulSoup(response.content, "xml")

entries = soup.find_all(["entry", "item"])

def get_text(entry, tag_names):
    for tag_name in tag_names:
        tag = entry.find(tag_name)

        if tag:
            # Atom author information may contain a nested <name> tag
            name_tag = tag.find("name")
            value = (
                name_tag.get_text(" ", strip=True)
                if name_tag else tag.get_text(" ", strip=True)
            )

            if value:
                return value

    return ""

def clean_summary(text):
    if not text:
        return ""

    text = BeautifulSoup(text, "html.parser").get_text(" ")
    return re.sub(r"\s+", " ", text).strip()

news_data = []

for entry in entries:
    title = get_text(entry, ["title"])
    author = get_text(entry, ["author", "dc:creator", "creator"])
    date = get_text(entry, ["published", "updated", "pubDate", "dc:date"])
    raw_summary = get_text(
        entry, ["summary", "description", "content:encoded"]
    )
    summary = clean_summary(raw_summary)

    # Skip articles without a usable summary
    if not summary:
        continue

    news_data.append({
        "title": title,
        "author": author if author else "Unknown",
        "publication_date": date,
        "summary": summary
    })

    if len(news_data) == 10:
        break

df = pd.DataFrame(
    news_data,
    columns=["title", "author", "publication_date", "summary"]
)

df.to_csv("tech_news.csv", index=False, encoding="utf-8")

