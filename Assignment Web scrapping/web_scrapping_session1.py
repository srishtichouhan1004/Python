import requests
from bs4 import BeautifulSoup

print("Libraries imported successfully!")

url = "https://www.flipkart.com/search?q=laptop"

response = requests.get(
    url,
    headers={"User-Agent": "Mozilla/5.0"},
    timeout=20
)

print("Status Code:", response.status_code)
print("Page URL:", response.url)
print("HTML downloaded:", len(response.text), "characters")

soup = BeautifulSoup(response.text, "html.parser")

# Display some heading elements
for tag in soup.find_all(["h1", "h2", "h3"])[:10]:
    print("Tag:", tag.name)
    print("Class:", tag.get("class"))
    print("Text:", tag.get_text(" ", strip=True))
    print("-" * 40)

# Search for elements with class attributes containing title-related words
for element in soup.find_all(class_=True):
    classes = " ".join(element.get("class", []))

    if "title" in classes.lower() or "product" in classes.lower():
        text = element.get_text(" ", strip=True)

        if text:
            print("Tag:", element.name)
            print("Class:", classes)
            print("Text:", text[:120])
            print("-" * 40)

url = "https://www.zomato.com/robots.txt"

response = requests.get(url, timeout=20)

print("Status Code:", response.status_code)
print("Content Type:", response.headers.get("Content-Type"))
print(response.text[:12000])

for line in response.text.splitlines():
    line = line.strip()

    if line.lower().startswith(
        ("user-agent:", "allow:", "disallow:", "sitemap:")
    ):
        print(line)

rules = [
    line.strip()
    for line in response.text.splitlines()
    if line.strip().lower().startswith(("allow:", "disallow:"))
]

print("Rules found:", len(rules))

for rule in rules[:2]:
    print(rule)

websites = {
    "Myntra": "https://www.myntra.com/",
    "Instagram": "https://www.instagram.com/"
}

pages = {}

for name, url in websites.items():
    try:
        response = requests.get(
            url,
            headers={"User-Agent": "Mozilla/5.0"},
            timeout=20
        )

        pages[name] = response.text

        print("\nWebsite:", name)
        print("Status Code:", response.status_code)
        print("HTML Size:", len(response.text), "characters")
        print("Content Type:", response.headers.get("Content-Type"))

    except requests.RequestException as error:
        print(name, "could not be accessed:", error)

for name, html in pages.items():
    soup = BeautifulSoup(html, "html.parser")

    print("\nWebsite:", name)
    print("Title:", soup.title.get_text(strip=True) if soup.title else "Not found")
    print("Images:", len(soup.find_all("img")))
    print("JavaScript files:", len(soup.find_all("script", src=True)))
    print("Links:", len(soup.find_all("a")))
    print("Text in initial HTML:",
          soup.get_text(" ", strip=True)[:250])

