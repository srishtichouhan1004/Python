import shutil
from selenium import webdriver
from selenium.webdriver.chrome.options import Options

def create_driver():
    options = Options()
    options.add_argument("--headless")
    options.add_argument("--no-sandbox")
    options.add_argument("--disable-dev-shm-usage")
    options.add_argument("--window-size=1365,1000")

    chrome_path = (
        shutil.which("chromium")
        or shutil.which("chromium-browser")
        or shutil.which("google-chrome")
    )

    if chrome_path:
        options.binary_location = chrome_path

    return webdriver.Chrome(options=options)

print("Selenium setup is ready!")

from selenium.webdriver.common.by import By
from selenium.webdriver.common.keys import Keys
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC

driver = create_driver()

try:
    driver.get("https://www.myntra.com/")

    wait = WebDriverWait(driver, 25)

    # Try common search-box selectors
    search_box = wait.until(
        EC.element_to_be_clickable((
            By.CSS_SELECTOR,
            "input.desktop-searchBar, input[placeholder*='Search'], input[type='text']"
        ))
    )

    search_box.click()
    search_box.send_keys("shoes")
    search_box.send_keys(Keys.ENTER)

    wait.until(lambda d: "shoes" in d.current_url.lower())

    print("Search submitted!")
    print("Current URL:", driver.current_url)

finally:
    driver.quit()

