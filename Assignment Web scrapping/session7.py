import time
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC

driver = create_driver()

try:
    driver.get("https://www.instagram.com/explore/")

    wait = WebDriverWait(driver, 20)
    wait.until(
        EC.presence_of_element_located((By.TAG_NAME, "body"))
    )

    collected_links = set()

    for scroll_number in range(1, 6):
        # Collect links currently available in the page
        links = driver.find_elements(
            By.CSS_SELECTOR,
            "a[href*='/p/'], a[href*='/reel/']"
        )

        for link in links:
            href = link.get_attribute("href")
            if href:
                collected_links.add(href.split("?")[0])

        print(
            f"After scroll {scroll_number}: "
            f"{len(collected_links)} unique post/Reel links"
        )

        # Scroll to the bottom to trigger more loading
        driver.execute_script(
            "window.scrollTo(0, document.body.scrollHeight)"
        )

        time.sleep(3)

    print("\nTotal unique links collected:", len(collected_links))

finally:
    driver.quit()

import time
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC

driver = create_driver()

try:
    driver.get("https://www.nykaa.com/search/result/?q=lipstick")

    wait = WebDriverWait(driver, 25)
    wait.until(
        EC.presence_of_element_located((By.TAG_NAME, "body"))
    )

    product_names = set()

    # Candidate selectors: update these if Nykaa changes its HTML
    selectors = [
        "[class*='productTitle']",
        "[class*='product-title']",
        "[class*='productName']",
        "a[href*='/p/']"
    ]

    for scroll_number in range(1, 16):
        for selector in selectors:
            elements = driver.find_elements(By.CSS_SELECTOR, selector)

            for element in elements:
                if not element.is_displayed():
                    continue

                name = (
                    element.get_attribute("title")
                    or element.text
                ).strip()

                # Ignore empty or overly long text
                if name and len(name) < 150:
                    product_names.add(name)

                if len(product_names) >= 30:
                    break

            if len(product_names) >= 30:
                break

        print(
            f"Scroll {scroll_number}: "
            f"{len(product_names)} unique candidate names"
        )

        if len(product_names) >= 30:
            break

        # Scroll down to trigger loading of more products
        driver.execute_script(
            "window.scrollTo(0, document.body.scrollHeight)"
        )
        time.sleep(3)

    print("\nProduct names collected:")
    for index, name in enumerate(sorted(product_names)[:30], start=1):
        print(f"{index}. {name}")

    print("\nTotal unique names printed:", min(len(product_names), 30))

    if len(product_names) < 30:
        print(
            "Fewer than 30 names were found. Inspect Nykaa's current "
            "product-card HTML and refine the selectors."
        )

finally:
    driver.quit()

