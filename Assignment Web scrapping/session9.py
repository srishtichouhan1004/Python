import pandas as pd

# Load IPL match statistics
df = pd.read_json("ipl_matches.json")

# Fill missing player names
df["player_name"] = (
    df["player_name"]
    .replace(r"^\s*$", pd.NA, regex=True)
    .fillna("Unknown")
)

# Export to a new JSON file
df.to_json(
    "ipl_matches_cleaned.json",
    orient="records",
    indent=4
)

print("Saved as ipl_matches_cleaned.json")
print(df.head())

import pandas as pd

# Load menu data
df = pd.read_csv("zomato_menu.csv")

# Remove rows with missing or blank ratings
df["rating"] = df["rating"].replace(r"^\s*$", pd.NA, regex=True)

df_cleaned = df.dropna(subset=["rating"])

