url2 = "https://httpbin.org/cookies"
response2 = session.get(url2)

print("Cookies received in second response:")
print(response2.json()["cookies"])

import requests

def check_status_code(url):
    try:
        response = requests.get(url, timeout=15)

        if response.status_code == 200:
            print("Success")
        elif response.status_code == 404:
            print("Not Found")
        else:
            print("Other Error")

    except requests.RequestException:
        print("Other Error")

check_status_code("https://jsonplaceholder.typicode.com/posts")

check_status_code("https://httpbin.org/status/404")

check_status_code("https://httpbin.org/status/500")

