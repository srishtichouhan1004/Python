from selenium import webdriver
from selenium.webdriver.chrome.options import Options
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC

options = Options()
options.add_argument("--headless")
options.add_argument("--no-sandbox")
options.add_argument("--disable-dev-shm-usage")

driver = webdriver.Chrome(options=options)

try:
    driver.get("https://www.zomato.com/")

    wait = WebDriverWait(driver, 20)

    # Find visible search inputs
    search_inputs = wait.until(
        EC.presence_of_all_elements_located(
            (By.CSS_SELECTOR, "input")
        )
    )

    for field in search_inputs:
        if field.is_displayed():
            placeholder = field.get_attribute("placeholder")
            if placeholder:
                print("Search placeholder:", placeholder)
                break
    else:
        print("No visible input with a placeholder was found.")

finally:
    driver.quit()

from selenium import webdriver
from selenium.webdriver.chrome.options import Options
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC
import time

options = Options()
options.add_argument("--headless")
options.add_argument("--no-sandbox")
options.add_argument("--disable-dev-shm-usage")
options.add_argument("--window-size=1365,1200")

driver = webdriver.Chrome(options=options)

try:
    driver.get("https://in.bookmyshow.com/")

    wait = WebDriverWait(driver, 20)
    wait.until(EC.presence_of_element_located((By.TAG_NAME, "body")))

    # Scroll down to trigger dynamic content
    driver.execute_script("window.scrollTo(0, 800);")
    time.sleep(3)

    # Scroll further to allow more content to load
    driver.execute_script("window.scrollTo(0, 1500);")
    time.sleep(2)

    # Common candidate selectors for movie cards/titles
    selectors = [
        "[class*='movie']",
        "[class*='Movie']",
        "[class*='title']"
    ]

    movie_names = []

    for selector in selectors:
        elements = driver.find_elements(By.CSS_SELECTOR, selector)

        for element in elements:
            if not element.is_displayed():
                continue

            text = element.text.strip()

            if text and len(text) < 100 and text not in movie_names:
                movie_names.append(text)

            if len(movie_names) == 5:
                break

        if len(movie_names) == 5:
            break

    if movie_names:
        print("First 5 candidate movie names:")
        for index, name in enumerate(movie_names, start=1):
            print(f"{index}. {name}")
    else:
        print("No movie names found. Inspect the current movie-card HTML.")

finally:
    driver.quit()

