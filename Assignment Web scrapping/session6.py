from selenium import webdriver
from selenium.webdriver.chrome.options import Options
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC
from IPython.display import display, Image

options = Options()
options.add_argument("--headless")
options.add_argument("--no-sandbox")
options.add_argument("--disable-dev-shm-usage")
options.add_argument("--window-size=1365,900")

driver = webdriver.Chrome(options=options)

try:
    # Open the demo login page
    driver.get("https://the-internet.herokuapp.com/login")

    wait = WebDriverWait(driver, 20)

    # Enter username
    username = wait.until(
        EC.visibility_of_element_located((By.ID, "username"))
    )
    username.send_keys("tomsmith")

    # Enter password
    password = driver.find_element(By.ID, "password")
    password.send_keys("SuperSecretPassword!")

    # Click Login
    driver.find_element(
        By.CSS_SELECTOR, "button[type='submit']"
    ).click()

    # Wait for the success message
    message = wait.until(
        EC.visibility_of_element_located((By.ID, "flash"))
    )

    print("Welcome message:")
    print(message.text.strip())

    # Capture screenshot of the successful login page
    screenshot_path = "/content/login_success.png"
    driver.save_screenshot(screenshot_path)

    print("\nScreenshot saved to:", screenshot_path)

    # Display the screenshot inside Colab
    display(Image(filename=screenshot_path))

finally:
    driver.quit()

