import requests
from bs4 import BeautifulSoup
import pandas as pd

url = "https://www.myntra.com/tshirts"

headers = {
    "User-Agent": "Mozilla/5.0"
}

response = requests.get(url, headers=headers, timeout=30)

print("Status Code:", response.status_code)

soup = BeautifulSoup(response.text, "html.parser")

products = []

# Myntra commonly uses product-productMetaInfo for product details
for card in soup.select("li.product-base"):
    brand_tag = card.select_one("h3.product-brand")
    name_tag = card.select_one("h4.product-product")
    price_tag = card.select_one(
        ".product-price span, .product-discountedPrice, .product-price"
    )

    if name_tag and price_tag:
        brand = brand_tag.get_text(strip=True) if brand_tag else ""
        name = name_tag.get_text(strip=True)
        price = price_tag.get_text(" ", strip=True)

        products.append({
            "Brand": brand,
            "Product": name,
            "Price": price
        })

    if len(products) == 20:
        break

if products:
    df = pd.DataFrame(products)
    display(df)
else:
    print("No products found in the returned HTML.")
    print("The page may require JavaScript or use different HTML selectors.")

import requests
from bs4 import BeautifulSoup
import pandas as pd
import time

base_url = "https://www.zomato.com/ahmedabad/restaurants/pizza"

headers = {
    "User-Agent": "Mozilla/5.0"
}

all_restaurants = []

for page in range(1, 4):
    print(f"\nScraping page {page}...")

    try:
        # Candidate pagination parameter: verify it on the live site
        response = requests.get(
            base_url,
            params={"page": page},
            headers=headers,
            timeout=30
        )

        print("Status code:", response.status_code)
        print("Requested URL:", response.url)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, "html.parser")

        # These are example selectors; inspect the current HTML
        cards = soup.select(
            "[data-testid*='restaurant'], "
            ".sc-1mo3ldo-0, "
            "article"
        )

        for card in cards:
            # Example approach: inspect the card's text and links
            name_tag = card.select_one(
                "h4, h5, [data-testid*='name']"
            )
            rating_tag = card.select_one(
                "[aria-label*='rating'], "
                "[class*='rating']"
            )

            if name_tag:
                name = name_tag.get_text(" ", strip=True)
                rating = (
                    rating_tag.get_text(" ", strip=True)
                    if rating_tag else "Not found"
                )

                all_restaurants.append({
                    "Page": page,
                    "Restaurant": name,
                    "Rating": rating
                })

    except requests.RequestException as error:
        print("Request failed:", error)

    # Required rate limiting between page requests
    if page < 3:
        time.sleep(2)

df_restaurants = pd.DataFrame(all_restaurants)

if not df_restaurants.empty:
    display(df_restaurants.drop_duplicates())
else:
    print(
        "No restaurant cards were extracted. "
        "Inspect the live HTML or Network requests and update "
        "the pagination method and selectors."
    )

import requests
from bs4 import BeautifulSoup
from urllib.parse import urljoin
import time

url = "https://books.toscrape.com/"

headers = {
    "User-Agent": "Mozilla/5.0"
}

product_titles = []

for page in range(1, 3):
    print(f"\nPage {page}")

    response = requests.get(
        url,
        headers=headers,
        timeout=30
    )

    response.raise_for_status()

    soup = BeautifulSoup(response.text, "html.parser")

    books = soup.select("article.product_pod")

    # Collect 3 titles from page 1 and 2 from page 2
    limit = 3 if page == 1 else 2

    for book in books[:limit]:
        title_tag = book.select_one("h3 a")

        if title_tag:
            title = title_tag.get("title") or title_tag.get_text(strip=True)
            product_titles.append(title)
            print(title)

    # Find the next page link
    next_link = soup.select_one("li.next a")

    if next_link:
        url = urljoin(url, next_link["href"])
    else:
        print("No next page found.")
        break

    # Wait before requesting the next page
    if page < 2:
        time.sleep(2)

print("\nTotal product titles collected:", len(product_titles))

