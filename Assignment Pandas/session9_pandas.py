import pandas as pd

zomato = pd.DataFrame({
    "user_id": [101, 102, 103, 104],
    "start_date": [
        "01-01-2026",
        "15-03-2026",
        "10-06-2026",
        "20-08-2026"
    ]
})


zomato["start_date"] = pd.to_datetime(
    zomato["start_date"],
    format="%d-%m-%Y"
)


today = pd.Timestamp.today().normalize()


zomato["tenure_days"] = (today - zomato["start_date"]).dt.days

print(zomato)

