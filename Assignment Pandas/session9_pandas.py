import pandas as pd

movies = pd.DataFrame({
    "movie": [
        "Inception",
        "Interstellar",
        "Titanic",
        "Avatar"
    ],
    "release_date": [
        "16-07-2010",
        "07-11-2014",
        "19-12-1997",
        "18-12-2009"
    ]
})

# Convert release_date to datetime
movies["release_date"] = pd.to_datetime(
    movies["release_date"],
    format="%d-%m-%Y"
)


movies["year"] = movies["release_date"].dt.year
movies["month"] = movies["release_date"].dt.month
movies["day"] = movies["release_date"].dt.day

print(movies)

