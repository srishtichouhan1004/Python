import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Load the dataset
# sep=None automatically detects common delimiters
bank_df = pd.read_csv("bank-full.csv", sep=None, engine="python")

# Display first 10 rows
print("First 10 rows:")
display(bank_df.head(10))

# Display DataFrame information
print("\nDataset Information:")
bank_df.info()

sns.set_theme(style="whitegrid")

plt.figure(figsize=(7, 5))

sns.countplot(
    data=bank_df,
    x="y",
    color="steelblue"
)

plt.title("Term Deposit Subscription Distribution")
plt.xlabel("Subscribed to Term Deposit?")
plt.ylabel("Number of Customers")
plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 5))

sns.boxplot(
    data=bank_df,
    x="y",
    y="age",
    color="lightblue"
)

plt.title("Customer Age by Term Deposit Subscription")
plt.xlabel("Subscribed to Term Deposit?")
plt.ylabel("Customer Age (years)")
plt.tight_layout()
plt.show()

# Calculate subscription percentage for each education level
education_summary = (
    bank_df.groupby("education", as_index=False)
    .agg(
        subscription_percentage=(
            "y",
            lambda values: values.eq("yes").mean() * 100
        )
    )
    .sort_values("subscription_percentage", ascending=False)
)

print(education_summary.round(2))

# Plot the percentages
plt.figure(figsize=(11, 6))

sns.barplot(
    data=education_summary,
    x="education",
    y="subscription_percentage",
    color="teal"
)

plt.title("Term Deposit Subscription Percentage by Education")
plt.xlabel("Education Level")
plt.ylabel("Customers Subscribed (%)")
plt.xticks(rotation=35, ha="right")
plt.tight_layout()
plt.show()

