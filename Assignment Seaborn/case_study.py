import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Create age groups
bank_df["age_group"] = pd.cut(
    bank_df["age"],
    bins=[0, 25, 35, 45, 55, 65, float("inf")],
    labels=[
        "Under 25",
        "25–34",
        "35–44",
        "45–54",
        "55–64",
        "65+"
    ],
    right=False
)

# Calculate subscription percentage by age group
age_summary = (
    bank_df.groupby("age_group", observed=False)
    .agg(
        subscription_percentage=(
            "y",
            lambda values: values.eq("yes").mean() * 100
        )
    )
    .reset_index()
)

print(age_summary.round(2))

# Plot subscription rates
sns.set_theme(style="whitegrid")

plt.figure(figsize=(10, 6))

sns.barplot(
    data=age_summary,
    x="age_group",
    y="subscription_percentage",
    color="cornflowerblue"
)

plt.title("Term Deposit Subscription Rate by Age Group")
plt.xlabel("Customer Age Group")
plt.ylabel("Subscription Rate (%)")
plt.tight_layout()
plt.show()

