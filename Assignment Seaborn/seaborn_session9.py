import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

np.random.seed(42)

# Create data for 24 students
n = 24

preparation_method = (
    ["self-study"] * 12 + ["coaching"] * 12
)

youtube_hours = np.concatenate([
    np.random.uniform(1, 6, 12),
    np.random.uniform(1, 6, 12)
])

# Sample scores: both groups have a negative trend,
# with different starting score levels
exam_scores = np.concatenate([
    90 - 6 * youtube_hours[:12]
    + np.random.normal(0, 4, 12),
    96 - 5 * youtube_hours[12:]
    + np.random.normal(0, 4, 12)
]).clip(30, 100).round(1)

df_students = pd.DataFrame({
    "youtube_hours": youtube_hours.round(1),
    "exam_score": exam_scores,
    "preparation_method": preparation_method
})

# Create faceted regression plots
g = sns.lmplot(
    data=df_students,
    x="youtube_hours",
    y="exam_score",
    col="preparation_method",
    height=4,
    aspect=1
)

g.set_axis_labels(
    "YouTube Hours per Day",
    "Exam Score"
)

g.set_titles("{col_name}")
g.fig.suptitle(
    "YouTube Viewing vs. Exam Scores by Preparation Method",
    y=1.08
)

plt.show()

