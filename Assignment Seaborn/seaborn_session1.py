import seaborn as sns
import matplotlib.pyplot as plt

days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
temps = [32, 34, 33, 35, 36, 37, 34]

themes = ["darkgrid", "whitegrid", "ticks"]

for theme in themes:
    # Apply the selected theme
    sns.set_theme(style=theme)

    # Create the chart
    fig, ax = plt.subplots(figsize=(8, 4))

    sns.lineplot(
        x=days,
        y=temps,
        marker="o",
        color="teal",
        ax=ax
    )

    ax.set_title(f"Weekly Temperature Trend - {theme}")
    ax.set_xlabel("Day")
    ax.set_ylabel("Temperature (°C)")

    fig.tight_layout()

    # Save each chart separately
    fig.savefig(
        f"temperature_{theme}.png",
        dpi=150,
        bbox_inches="tight"
    )

    plt.show()
    plt.close(fig)

