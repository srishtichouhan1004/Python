import seaborn as sns
import matplotlib.pyplot as plt

# Load the built-in tips dataset
tips = sns.load_dataset("tips")

# Display first five rows
print(tips.head())

# Create pairplot for all numerical columns
sns.pairplot(tips)

plt.show()

sns.pairplot(
    tips,
    hue="gender"
)

plt.show()

sns.pairplot(
    tips,
    hue="smoker",
    diag_kind="kde"
)

plt.show()

sns.pairplot(
    tips,
    vars=["total_bill", "tip"],
    hue="time"
)

plt.show()

