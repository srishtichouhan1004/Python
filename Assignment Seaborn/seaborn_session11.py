import seaborn as sns
import matplotlib.pyplot as plt

def apply_presentation_theme():
    """Apply a consistent presentation-ready Seaborn theme."""
    sns.set_theme(
        style="whitegrid",
        context="talk",
        palette="deep",
        font="DejaVu Sans",
        rc={
            "axes.titleweight": "bold",
            "figure.figsize": (9, 6)
        }
    )

# Apply the theme
apply_presentation_theme()

# Sample app usage in hours per week
apps = ["Instagram", "YouTube", "WhatsApp", "Spotify", "Chrome"]
usage_hours = [12, 10, 8, 5, 4]

plt.figure(figsize=(9, 7))

colors = sns.color_palette("deep", n_colors=5)

plt.pie(
    usage_hours,
    labels=apps,
    autopct="%1.1f%%",
    startangle=90,
    colors=colors
)

plt.title("Top 5 Most-Used Apps")
plt.tight_layout()

# Export pie chart
plt.savefig("top_5_apps.png", dpi=300, bbox_inches="tight")
plt.show()

import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# ChatGPT prompt:
# "Generate Python code to create a Seaborn correlation heatmap
# with annotations and export it as an SVG file at 1200 DPI."

# ChatGPT-generated and adapted code:
# Create sample product dataset
df = pd.DataFrame({
    "Price": [100, 200, 300, 400, 500],
    "Rating": [3.5, 4.0, 4.2, 3.8, 4.5],
    "Reviews": [50, 100, 180, 160, 300],
    "Discount": [10, 15, 20, 25, 30]
})

# Calculate correlation matrix
corr = df.corr()

sns.set_theme(style="white")

plt.figure(figsize=(8, 6))

sns.heatmap(
    corr,
    annot=True,
    fmt=".2f",
    cmap="coolwarm",
    vmin=-1,
    vmax=1,
    center=0,
    linewidths=0.5
)

plt.title("Product Features Correlation Heatmap")
plt.tight_layout()

# Save as SVG at 1200 DPI
plt.savefig(
    "correlation_heatmap.svg",
    format="svg",
    dpi=1200,
    bbox_inches="tight"
)

plt.show()

