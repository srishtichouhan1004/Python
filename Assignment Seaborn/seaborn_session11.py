import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Sample food delivery data
df = pd.DataFrame({
    "Food_Category": ["Pizza", "Burger", "Biryani", "Momos", "Ice Cream"],
    "Orders": [120, 150, 100, 90, 80]
})

sns.set_theme(style="whitegrid", palette="deep")

plt.figure(figsize=(9, 5))
sns.barplot(data=df, x="Food_Category", y="Orders")

plt.title("Number of Orders by Food Category")
plt.xlabel("Food Category")
plt.ylabel("Number of Orders")
plt.tight_layout()

# Save as PNG at 300 DPI
plt.savefig("food_category_orders.png", dpi=300, bbox_inches="tight")
plt.show()

