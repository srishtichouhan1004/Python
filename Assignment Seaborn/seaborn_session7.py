import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

# Generate reproducible sample data
np.random.seed(42)

n = 20

delivery_distance = np.random.uniform(1, 12, n).round(1)

delivery_time = (
    15 + 4 * delivery_distance
    + np.random.normal(0, 3, n)
).round(1)

order_value = np.random.randint(100, 1000, n)

tip_amount = (
    order_value * 0.08
    + np.random.normal(0, 10, n)
).clip(0).round(1)

rating = (
    5.5 - 0.045 * delivery_time
    + np.random.normal(0, 0.15, n)
).clip(1, 5).round(1)

# Create DataFrame
food_data = pd.DataFrame({
    "delivery_time": delivery_time,
    "order_value": order_value,
    "tip_amount": tip_amount,
    "rating": rating,
    "delivery_distance": delivery_distance
})

print("Food Delivery Dataset:")
print(food_data)

# Calculate correlation matrix
correlation_matrix = food_data.corr()

print("\nCorrelation Matrix:")
print(correlation_matrix.round(2))

plt.figure(figsize=(9, 6))

sns.heatmap(
    correlation_matrix,
    annot=True,
    fmt=".2f",
    cmap="coolwarm",
    linewidths=0.5
)

plt.title("Food Delivery Features - Correlation Heatmap")
plt.tight_layout()
plt.show()

plt.figure(figsize=(9, 6))

sns.heatmap(
    correlation_matrix,
    annot=True,
    fmt=".2f",
    cmap="RdYlGn",
    vmin=-1,
    vmax=1,
    center=0,
    linewidths=0.5
)

plt.title("Food Delivery Correlation Heatmap")
plt.tight_layout()
plt.show()

# Find the strongest negative correlation
# Ignore the diagonal and duplicate pairs
upper_triangle = correlation_matrix.where(
    np.triu(np.ones(correlation_matrix.shape), k=1).astype(bool)
)

negative_correlations = upper_triangle.stack()
negative_correlations = negative_correlations[
    negative_correlations < 0
]

if not negative_correlations.empty:
    strongest_pair = negative_correlations.idxmin()
    strongest_value = negative_correlations.min()

    print("Strongest negative correlation:")
    print(f"Features: {strongest_pair[0]} and {strongest_pair[1]}")
    print(f"Correlation: {strongest_value:.2f}")
else:
    print("No negative correlations found.")

