# Compare different bin sizes
fig, axes = plt.subplots(1, 3, figsize=(15, 4))

bin_values = [5, 10, 20]

for ax, bins in zip(axes, bin_values):
    sns.histplot(
        x=ipl_scores,
        bins=bins,
        ax=ax,
        edgecolor="black"
    )
    ax.set_title(f"IPL Scores: {bins} Bins")
    ax.set_xlabel("Runs Scored")
    ax.set_ylabel("Number of Innings")

plt.tight_layout()
