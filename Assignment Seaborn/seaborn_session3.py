df_zomato = pd.DataFrame({
    "Monthly_Spending": monthly_spending
})

# Create histogram and KDE curve on the same axes
sns.histplot(
    data=df_zomato,
    x="Monthly_Spending",
    bins=8,
    stat="density",
    color="skyblue",
    alpha=0.5
)

sns.kdeplot(
    data=df_zomato,
    x="Monthly_Spending",
    color="red",
    linewidth=2
)

plt.title("Distribution of Monthly Zomato Spending")
plt.xlabel("Spending Amount (₹)")
plt.ylabel("Probability Density")
plt.show()

import seaborn as sns
