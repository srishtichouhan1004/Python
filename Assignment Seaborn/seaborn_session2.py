import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Sample Swiggy orders dataset
swiggy_data = {
    "Order_ID": [101, 102, 103, 104, 105, 106, 107, 108, 109, 110],
    "Payment_Method": [
        "UPI", "Card", "Cash", "UPI", "UPI",
        "Card", "Cash", "UPI", "Card", "Cash"
    ]
}

df_swiggy = pd.DataFrame(swiggy_data)

# Create countplot
sns.countplot(data=df_swiggy, x="Payment_Method")

plt.title("Number of Orders by Payment Method")
plt.xlabel("Payment Method")
plt.ylabel("Number of Orders")
plt.show()

import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Sample Zomato-style dataset
zomato_data = {
    "Food_Category": [
        "Pizza", "Pizza", "Pizza",
        "Burger", "Burger", "Burger",
        "Biryani", "Biryani", "Biryani",
        "South Indian", "South Indian", "South Indian"
    ],
    "Delivery_Time": [
        30, 35, 25,
        20, 25, 30,
        40, 45, 35,
        25, 20, 30
    ]
}

df_zomato = pd.DataFrame(zomato_data)

# Plot average delivery time
sns.barplot(
    data=df_zomato,
    x="Food_Category",
    y="Delivery_Time",
    estimator="mean",
    errorbar=None
)

plt.title("Average Delivery Time by Food Category")
plt.xlabel("Food Category")
plt.ylabel("Average Delivery Time (minutes)")
plt.show()

# Count the number of orders in each food category
order_counts = df_zomato["Food_Category"].value_counts()

# Create a DataFrame for plotting
orders_df = order_counts.reset_index()
orders_df.columns = ["Food_Category", "Total_Orders"]

# Plot total orders
sns.barplot(
    data=orders_df,
    x="Food_Category",
    y="Total_Orders",
    errorbar=None
)

plt.title("Total Orders by Food Category")
plt.xlabel("Food Category")
plt.ylabel("Total Number of Orders")
plt.show()

