import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Sample sales data
sales_data = {
    "Category": [
        "Mobiles", "Laptops", "Clothing",
        "Home Appliances", "Accessories"
    ],
    "Sales": [250000, 320000, 180000, 210000, 140000]
}

df_sales = pd.DataFrame(sales_data)

# Set custom dashboard theme
sns.set(
    context="talk",
    style="whitegrid",
    palette="deep",
    font_scale=1.1,
    rc={
        "axes.titleweight": "bold",
        "axes.labelweight": "bold",
        "grid.linestyle": "--",
        "grid.alpha": 0.4,
        "figure.figsize": (10, 6)
    }
)

# Create barplot
sns.barplot(
    data=df_sales,
    x="Category",
    y="Sales"
)

plt.title("Flipkart-Style Product Category Sales")
plt.xlabel("Product Category")
plt.ylabel("Sales (₹)")
plt.xticks(rotation=15)
plt.tight_layout()
plt.show()

# Reset settings for future plots
sns.set_theme()

