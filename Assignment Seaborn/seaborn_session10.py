import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Sample Spotify streaming data
spotify_data = {
    "Day": ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"],
    "Songs_Streamed": [45, 52, 48, 60, 75, 90, 82]
}

df_spotify = pd.DataFrame(spotify_data)

# Apply poster context
sns.set(context="poster")

# Create barplot
sns.barplot(
    data=df_spotify,
    x="Day",
    y="Songs_Streamed"
)

plt.title("Daily Songs Streamed on Spotify")
plt.xlabel("Day")
plt.ylabel("Number of Songs Streamed")
plt.tight_layout()
plt.show()

# Reset to default settings for subsequent plots
sns.set_theme()

